"""Frozen interface protocols (owner: orchestrator; Review 5B Implementation §11.1).

Implementations by workstream:
- `NativeDomain`      -> autoontobench/core/domains/<source_id>.py     (owners: W2 / W3 / W4)
- `OntologyTool`      -> autoontobench/core/ontology_consumer.py       (owner: W6)
- `ResearcherHarness` -> autoontobench/runners/<arm>.py                (owner: W6)

Contract rules (binding):
- `NativeDomain.legal_action` / `.verify_terminal` are the INDEPENDENT terminal ground truth.
  They must not call `OntologyTool`; `OntologyTool` must not call them.
- `empty()/reset()` must return an immutable snapshot; every step persists before/after checksums;
  actions outside the manifest allowlist are rejected.
- `validate_artifact()` may never reveal gold, native rules or hidden witnesses.

Do NOT edit this file; interface changes go through the orchestrator.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Protocol, runtime_checkable

from autoontobench.contracts.models import GoalResult, TaskSpecV5

# ---- lightweight types ------------------------------------------------------------
TypedAction = dict[str, Any]
PermissionSet = set[str]
ContentHash = str


@dataclass(frozen=True)
class NativeState:
    payload: dict[str, Any]


@dataclass(frozen=True)
class PublicObservation:
    payload: dict[str, Any]


@dataclass(frozen=True)
class NativeDecision:
    legal: bool | None            # None => UNKNOWN under native semantics
    detail: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class NativeStateAndFeedback:
    state: NativeState
    feedback: dict[str, Any]
    cost: float = 0.0


@dataclass(frozen=True)
class ValidatedOntology:
    profile: str
    artifact_bytes: bytes
    content_hash: ContentHash
    handle: Any = None


@dataclass(frozen=True)
class OntologyPrediction:
    prediction: Any
    detail: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class Budget:
    oracle_probes: int = 8
    total_tool_calls: int = 32
    max_actions: int = 12
    max_output_tokens: int = 12000


@dataclass(frozen=True)
class PublicTask:
    task_id: str
    public_spec: dict[str, Any]
    root: str


@dataclass
class SealedRun:
    run_id: str
    task_id: str
    arm: str
    rows: list[dict[str, Any]] = field(default_factory=list)
    terminal_state_sha: str | None = None
    final_answer: Any = None
    status: str = "PENDING"


# ---- protocols ---------------------------------------------------------------------
@runtime_checkable
class NativeDomain(Protocol):
    def reset(self, spec: TaskSpecV5, seed: int) -> NativeState: ...
    def observe(self, state: NativeState, rights: PermissionSet) -> PublicObservation: ...
    def legal_action(self, state: NativeState, action: TypedAction) -> NativeDecision: ...
    def step(self, state: NativeState, action: TypedAction) -> NativeStateAndFeedback: ...
    def verify_terminal(
        self, spec: TaskSpecV5, state: NativeState, submitted_answer: object
    ) -> GoalResult: ...


@runtime_checkable
class OntologyTool(Protocol):
    def load(self, public_artifact_bytes: bytes, named_profile: str) -> ValidatedOntology: ...
    def query_or_check(
        self, artifact: ValidatedOntology, public_facts: object, request: object
    ) -> OntologyPrediction: ...
    def seal(self, artifact: ValidatedOntology) -> ContentHash: ...


@runtime_checkable
class ResearcherHarness(Protocol):
    def run(
        self, task_public_spec: PublicTask, model: Any, arm: str, budget: Budget
    ) -> SealedRun: ...