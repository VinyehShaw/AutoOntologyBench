"""latex: LaTeX macro/table rendering for the P8 exporter (Shared Contract §G).

Renders ``paper_macros.tex`` and ``tables/*.tex`` skeletons. Any metric without
claimable measured runs renders as ``\\AobPending`` — the paper must never show
a guessed number (§G: "Replace old SIM numerical cells with PENDING macros").
"""
from __future__ import annotations

from typing import Any, Dict

from autoontobench.export.aggregate import LoadReport
from autoontobench.export.interfaces import PLANNED_SOURCES, STATUS_MEASURED


def _macro_suffix(arm: str) -> str:
    return "".join(part.capitalize() for part in arm.replace("+", "_").split("_"))


def render_macros(main_tsr: Dict[str, Any], claimable_runs: int, dev_mock_runs: int) -> str:
    lines = [
        "% Auto-generated by autoontobench.export (P8). DO NOT hand-edit.",
        f"% input_digest: {main_tsr['input_digest']}",
        "% \\AobPending marks a cell with no claimable measured runs (never 0, never simulated).",
        "\\providecommand{\\AobPending}{\\textit{PENDING}}",
        f"\\newcommand{{\\AobClaimableRuns}}{{{claimable_runs}}}",
        f"\\newcommand{{\\AobDevMockRuns}}{{{dev_mock_runs}}}",
        f"\\newcommand{{\\AobInputDigest}}{{{main_tsr['input_digest'][:16]}}}",
    ]
    for cell in main_tsr["cells"]:
        suffix = _macro_suffix(cell["arm"])
        lines.append(f"\\newcommand{{\\AobLaunched{suffix}}}{{{cell['launched']}}}")
        if cell["status"] == STATUS_MEASURED:
            lines.append(f"\\newcommand{{\\AobTsr{suffix}}}{{{cell['tsr']:.3f}}}")
            lines.append(f"\\newcommand{{\\AobVTsr{suffix}}}{{{cell['v_tsr']:.3f}}}")
        else:
            lines.append(f"\\newcommand{{\\AobTsr{suffix}}}{{\\AobPending}}")
            lines.append(f"\\newcommand{{\\AobVTsr{suffix}}}{{\\AobPending}}")
    return "\n".join(lines) + "\n"


def render_main_results_table(main_tsr: Dict[str, Any]) -> str:
    lines = [
        "% Auto-generated by autoontobench.export (P8). DO NOT hand-edit.",
        "% Main results skeleton: cells are \\AobPending until claimable runs exist.",
        "\\begin{tabular}{lrrrr}",
        "\\hline",
        "Arm & Launched & Scored & TSR & V-TSR \\\\",
        "\\hline",
    ]
    for cell in main_tsr["cells"]:
        suffix = _macro_suffix(cell["arm"])
        lines.append(
            f"{cell['arm']} & \\AobLaunched{suffix} & {cell['scored']} "
            f"& \\AobTsr{suffix} & \\AobVTsr{suffix} \\\\"
        )
    lines += ["\\hline", "\\end{tabular}", ""]
    return "\n".join(lines)


def render_source_yield_table() -> str:
    lines = [
        "% Auto-generated by autoontobench.export (P8). DO NOT hand-edit.",
        "% Source provenance/yield skeleton: qualification yields are PENDING",
        "% until per-source funnels produce claimable, source-hash-pinned rows.",
        "\\begin{tabular}{lll}",
        "\\hline",
        "Source & Qualified yield & Status \\\\",
        "\\hline",
    ]
    for src in PLANNED_SOURCES:
        lines.append(f"{src} & \\AobPending & PENDING \\\\")
    lines += ["\\hline", "\\end{tabular}", ""]
    return "\n".join(lines)
