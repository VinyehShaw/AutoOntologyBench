"""Render the generated license-layer documents (NOTICE, ATTRIBUTION, SUMMARY).

All renderers are pure functions of the license registry plus the assembled
worlds, with sorted iteration and no timestamps, so rebuilds stay
byte-identical.
"""

from __future__ import annotations

from .license_registry import SourceLicense, resolve_world
from .validate import ValidatedWorld

_NOTICE_HEADER = """\
AutoOntologyBench - Core-track benchmark release
Copyright 2026 AutoOntologyBench contributors

The project code is licensed under Apache-2.0 (see LICENSE); the
benchmark data is released under CC BY 4.0 (see LICENSE-DATA.md). This
posture follows the repository's recorded recommendation
(reports/w7_license_recommendation.md, DRAFT) - PI sign-off is PENDING;
treat this release as pre-publication packaging until sign-off is
recorded.

This release contains task records and public materials derived from or
referencing the third-party sources below. Full license texts and
per-source summaries are in LICENSES/.
"""

_ATTRIBUTION_HEADER = """\
# ATTRIBUTION - AutoOntologyBench Core-track benchmark release

Generated by `scripts/assemble_core_release.py` from each world pack's
`manifests/provenance.json` license declaration and the pinned source
snapshot evidence. Per-source details: `LICENSES/<source_id>/SUMMARY.md`.
Every world license reference is resolved in
`worlds/<world_id>/metadata.json::license_attribution` (shipped into this
release, or explicitly marked not shipped with a reason); verify with
`scripts/check_core_license_pointers.py`.
"""


def _worlds_by_source(
    sources: dict[str, SourceLicense], worlds: list[ValidatedWorld]
) -> dict[str, list[str]]:
    return {
        source_id: sorted(
            world.world_id
            for world in worlds
            if source_id in resolve_world(world.world_id).sources
        )
        for source_id in sources
    }


def render_notice(sources: dict[str, SourceLicense], worlds: list[ValidatedWorld]) -> str:
    """Top-level NOTICE: project grant plus one block per upstream source."""
    lines = [_NOTICE_HEADER.rstrip("\n"), ""]
    by_source = _worlds_by_source(sources, worlds)
    for source_id, source in sources.items():
        lines.append(f"== {source_id} ({', '.join(by_source[source_id])})")
        lines.append(f"   License: {source.license_label}")
        lines.append(f"   Attribution: {source.attribution}")
        lines.append(f"   Obligation: {source.obligation}")
        lines.append(f"   Details: LICENSES/{source_id}/SUMMARY.md")
        lines.append("")
    return "\n".join(lines)


def render_attribution(worlds: list[ValidatedWorld], sources: dict[str, SourceLicense]) -> str:
    """LICENSES/ATTRIBUTION.md master table, citations, and open items."""
    lines = [
        _ATTRIBUTION_HEADER.rstrip("\n"),
        "",
        "| world | source | license | bundle |",
        "|---|---|---|---|",
    ]
    for world in worlds:
        for source_id in resolve_world(world.world_id).sources:
            source = sources[source_id]
            lines.append(
                f"| {world.world_id} | {source_id} | {source.license_label} | "
                f"`LICENSES/{source_id}/` |"
            )
    lines.append("")
    citations = [
        (source_id, citation)
        for source_id, source in sources.items()
        for citation in source.citations
    ]
    if citations:
        lines.append("## Key citations")
        lines.append("")
        lines.extend(f"- **{source_id}**: {citation}" for source_id, citation in citations)
        lines.append("")
    open_items = [
        (source_id, note)
        for source_id, source in sources.items()
        for note in source.notes
    ]
    if open_items:
        lines.append("## Recorded notes and open items")
        lines.append("")
        lines.extend(f"- **{source_id}**: {note}" for source_id, note in open_items)
        lines.append("")
    return "\n".join(lines)


def render_summary(source: SourceLicense, worlds: list[ValidatedWorld]) -> str:
    """LICENSES/<source_id>/SUMMARY.md: posture, declared strings, provenance."""
    users = [
        world
        for world in worlds
        if source.source_id in resolve_world(world.world_id).sources
    ]
    lines = [
        f"# {source.source_id}",
        "",
        f"- Worlds using this source: {', '.join(world.world_id for world in users)}",
        f"- License: {source.license_label}",
        f"- Attribution: {source.attribution}",
        f"- Redistribution obligation: {source.obligation}",
        "",
        "License as declared in each world's `metadata.json::license`:",
        "",
    ]
    lines.extend(
        f"- {world.world_id}: \"{world.provenance.get('license')}\"" for world in users
    )
    lines.append("")
    lines.append("## Pinned evidence shipped in this directory")
    lines.append("")
    lines.extend(
        f"- `{bundle_file.dest}` - {bundle_file.note} (origin: `{bundle_file.origin}`)"
        for bundle_file in source.files
    )
    lines.append("")
    if source.notes:
        lines.append("## Notes")
        lines.append("")
        lines.extend(f"- {note}" for note in source.notes)
        lines.append("")
    if source.citations:
        lines.append("## Citations")
        lines.append("")
        lines.extend(f"- {citation}" for citation in source.citations)
        lines.append("")
    return "\n".join(lines)


__all__ = ["render_attribution", "render_notice", "render_summary"]
